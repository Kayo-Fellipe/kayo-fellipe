class Portfolio {
  constructor() {
    this.currentProject = null;
    this.currentIndex = 0;
    this.portfolioItems = [];
    this.touchStartX = 0;
    this.touchEndX = 0;
    this.touchStartY = 0;
    this.touchEndY = 0;
    this.init();
  }

  init() {
    this.portfolioItems = Array.from(document.querySelectorAll('.portfolio-item'));
    this.bindEvents();
  }

  bindEvents() {
    const portfolioItems = document.querySelectorAll('.portfolio-item');
    portfolioItems.forEach(item => {
      item.addEventListener('click', (e) => {
        e.preventDefault();
        const projectId = item.getAttribute('data-project');
        if (projectId) {
          this.openGallery(projectId);
        }
      });
    });

    const modal = document.getElementById('gallery-modal');
    const closeBtn = document.getElementById('close-modal');
    const prevBtn = document.getElementById('prev-btn');
    const nextBtn = document.getElementById('next-btn');

    if (closeBtn) closeBtn.addEventListener('click', () => this.closeGallery());
    if (prevBtn) prevBtn.addEventListener('click', () => this.previousItem());
    if (nextBtn) nextBtn.addEventListener('click', () => this.nextItem());

    if (modal) {
      modal.addEventListener('click', (e) => {
        if (e.target === modal) {
          this.closeGallery();
        }
      });
    }

    document.addEventListener('keydown', (e) => {
      if (modal && modal.classList.contains('active')) {
        switch(e.key) {
          case 'Escape': this.closeGallery(); break;
          case 'ArrowLeft': this.previousItem(); break;
          case 'ArrowRight': this.nextItem(); break;
        }
      }
    });

    this.setupTouchNavigation();
  }

  setupTouchNavigation() {
    const galleryMain = document.getElementById('gallery-main');
    if (!galleryMain) return;

    let isSwiping = false;

    galleryMain.addEventListener('touchstart', (e) => {
      this.touchStartX = e.changedTouches[0].screenX;
      this.touchStartY = e.changedTouches[0].screenY;
      isSwiping = false;

      const indicator = document.querySelector('.swipe-indicator');
      if (indicator) indicator.style.display = 'none';
    }, { passive: true });

    galleryMain.addEventListener('touchmove', (e) => {
      if (!this.touchStartX) return;

      const currentX = e.changedTouches[0].screenX;
      const currentY = e.changedTouches[0].screenY;
      const diffX = Math.abs(currentX - this.touchStartX);
      const diffY = Math.abs(currentY - this.touchStartY);

      if (diffX > diffY && diffX > 20) {
        e.preventDefault();
        isSwiping = true;

        const img = galleryMain.querySelector('img');
        if (img) {
          galleryMain.classList.add('swiping');
          const direction = currentX > this.touchStartX ? 'right' : 'left';
          img.classList.remove('swipe-left', 'swipe-right');
          img.classList.add(`swipe-${direction}`);
        }
      }
    }, { passive: false });

    galleryMain.addEventListener('touchend', (e) => {
      if (!this.touchStartX) return;

      this.touchEndX = e.changedTouches[0].screenX;
      this.touchEndY = e.changedTouches[0].screenY;

      const img = galleryMain.querySelector('img');
      if (img) {
        galleryMain.classList.remove('swiping');
        img.classList.remove('swipe-left', 'swipe-right');
      }

      if (isSwiping) {
        this.handleSwipe();
      }

      this.touchStartX = 0;
      this.touchEndX = 0;
      this.touchStartY = 0;
      this.touchEndY = 0;
      isSwiping = false;
    }, { passive: true });

    // Mouse swipe for desktop
    let mouseStartX = 0;
    let isMouseSwiping = false;

    galleryMain.addEventListener('mousedown', (e) => {
      mouseStartX = e.clientX;
      isMouseSwiping = true;
      e.preventDefault();
    });

    galleryMain.addEventListener('mousemove', (e) => {
      if (!isMouseSwiping) return;
      const diffX = Math.abs(e.clientX - mouseStartX);
      if (diffX > 10) {
        const img = galleryMain.querySelector('img');
        if (img) {
          galleryMain.classList.add('swiping');
          const direction = e.clientX > mouseStartX ? 'right' : 'left';
          img.classList.remove('swipe-left', 'swipe-right');
          img.classList.add(`swipe-${direction}`);
        }
      }
    });

    galleryMain.addEventListener('mouseup', (e) => {
      if (!isMouseSwiping) return;
      const diffX = e.clientX - mouseStartX;

      const img = galleryMain.querySelector('img');
      if (img) {
        galleryMain.classList.remove('swiping');
        img.classList.remove('swipe-left', 'swipe-right');
      }

      if (Math.abs(diffX) > 50) {
        if (diffX > 0) this.previousItem();
        else this.nextItem();
      }

      isMouseSwiping = false;
      mouseStartX = 0;
    });

    galleryMain.addEventListener('contextmenu', (e) => e.preventDefault());
  }

  handleSwipe() {
    const swipeThreshold = 80;
    const diffX = this.touchEndX - this.touchStartX;
    const diffY = Math.abs(this.touchEndY - this.touchStartY);

    if (Math.abs(diffX) > swipeThreshold && Math.abs(diffX) > diffY) {
      if (diffX > 0) this.previousItem();
      else this.nextItem();
    }
  }

  openGallery(projectId) {
    const project = portfolioData[projectId];
    if (!project) return;

    this.currentProject = project;
    this.currentIndex = 0;

    const titleEl = document.getElementById('gallery-title');
    titleEl.innerHTML = project.title + (project.titleSerif ? ` <span class="serif">${project.titleSerif}</span>` : '');
    document.getElementById('total-items').textContent = project.items.length;

    this.generateThumbnails();
    this.showCurrentItem();

    const modal = document.getElementById('gallery-modal');
    modal.classList.add('active');
    document.body.style.overflow = 'hidden';

    this.updateNavigation();
  }

  closeGallery() {
    const modal = document.getElementById('gallery-modal');
    modal.classList.remove('active');
    document.body.style.overflow = 'auto';

    const iframes = modal.querySelectorAll('iframe');
    iframes.forEach(iframe => { iframe.src = ''; });

    this.currentProject = null;
    this.currentIndex = 0;
  }

  showCurrentItem() {
    if (!this.currentProject) return;

    const item = this.currentProject.items[this.currentIndex];
    const galleryMain = document.getElementById('gallery-main');

    document.getElementById('current-index').textContent = this.currentIndex + 1;
    galleryMain.innerHTML = '';

    if (item.type === 'image') {
      const img = document.createElement('img');
      img.src = item.src;
      img.alt = this.currentProject.title;
      img.style.opacity = '0';
      img.style.transition = 'opacity 0.4s ease';
      img.addEventListener('load', () => { img.style.opacity = '1'; });
      galleryMain.appendChild(img);
    } else if (item.type === 'video') {
      const iframe = document.createElement('iframe');
      iframe.src = item.src;
      iframe.allow = 'autoplay; fullscreen; picture-in-picture';
      iframe.allowFullscreen = true;
      galleryMain.appendChild(iframe);
    } else if (item.type === 'youtube') {
      const iframe = document.createElement('iframe');
      iframe.src = convertYouTubeUrl(item.src);
      iframe.allow = 'autoplay; fullscreen; picture-in-picture';
      iframe.allowFullscreen = true;
      galleryMain.appendChild(iframe);
    } else if (item.type === 'external-link') {
      const linkContainer = document.createElement('div');
      linkContainer.className = 'external-link-container';
      linkContainer.innerHTML = `
        <div class="external-link-content">
          <i class="fas fa-external-link-alt"></i>
          <h3>${item.title || 'Ver Conteúdo Externo'}</h3>
          <p>Este conteúdo está hospedado externamente</p>
          <a href="${item.src}" target="_blank" class="btn btn-primary">
            <i class="fas fa-arrow-right"></i> Abrir Link
          </a>
        </div>
      `;
      galleryMain.appendChild(linkContainer);
    }

    this.updateThumbnailActive();
    this.updateNavigation();
  }

  generateThumbnails() {
    const thumbnailsContainer = document.getElementById('gallery-thumbnails');
    thumbnailsContainer.innerHTML = '';

    this.currentProject.items.forEach((item, index) => {
      const thumbnail = document.createElement('div');
      thumbnail.className = `thumbnail ${item.type}`;
      if (index === 0) thumbnail.classList.add('active');

      const img = document.createElement('img');
      img.src = item.thumbnail;
      img.alt = `${this.currentProject.title} ${index + 1}`;
      img.loading = 'lazy';

      thumbnail.appendChild(img);
      thumbnail.addEventListener('click', () => {
        this.currentIndex = index;
        this.showCurrentItem();
      });

      thumbnailsContainer.appendChild(thumbnail);
    });
  }

  updateThumbnailActive() {
    const thumbnails = document.querySelectorAll('.thumbnail');
    thumbnails.forEach((thumb, index) => {
      thumb.classList.toggle('active', index === this.currentIndex);
    });
  }

  previousItem() {
    if (!this.currentProject || this.currentIndex <= 0) return;
    this.currentIndex--;
    this.showCurrentItem();
  }

  nextItem() {
    if (!this.currentProject || this.currentIndex >= this.currentProject.items.length - 1) return;
    this.currentIndex++;
    this.showCurrentItem();
  }

  updateNavigation() {
    const prevBtn = document.getElementById('prev-btn');
    const nextBtn = document.getElementById('next-btn');

    if (!this.currentProject) return;

    if (prevBtn) prevBtn.disabled = this.currentIndex <= 0;
    if (nextBtn) nextBtn.disabled = this.currentIndex >= this.currentProject.items.length - 1;
  }
}

